// ПРЕМАТЧ: правила расчёта. Рынок может называться одинаково, а рассчитываться у контор по-разному — тогда цена
// Pinnacle не годится как противоположная ставка, и «вилка» ложная при верном сопоставлении. Чистая логика.
//
// Источник Pinnacle — официальная страница правил pinnacle.com/en/future/betting-rules (прочитана 22.11.2026).
// Правила Betano прочитать не удалось: страницы закрыты блокировкой по стране. Там, где правило Betano неизвестно,
// рынок ИСКЛЮЧАЕТСЯ (лучше пропустить, чем поставить на несопоставимое). Что проверено по ценам самого Betano —
// отмечено отдельно.
//
// ЧТО СОПОСТАВИМО (проверено):
//  • Футбол: все рынки матча — основное время (Pinnacle: «scheduled 90 minutes… does not include extra time»).
//  • Победа в половине/четверти/периоде без ничьей («… Winner» у Betano против двухисходного рынка Pinnacle).
//    Pinnacle, общее правило 8: ничьей в линии нет и она случилась — обе ставки аннулируются. У Betano то же:
//    цена «Winner» ниже цены «Result» ровно на вероятность ничьей (замер на дампе 19.11.2026: баскетбол, первая
//    четверть — отношение 0.956 при ожидаемом 0.932 для «ничья = возврат» и 1.000 для «ничья = проигрыш»).
//  • Овертайм: у Pinnacle ставки на игру включают овертайм (баскетбол, ам. футбол, хоккей — и буллиты). В фиде такие
//    рынки лежат в сегменте «…/Overtime», рынки основного времени — отдельно («Goals (Regular Time)» у Betano).
//
// ЧТО ИСКЛЮЧЕНО:
//  • Теннис, ПАРНЫЕ матчи — фора и тотал по геймам за матч. Pinnacle, теннис, правило 4: если решающий сет
//    заменён тай-брейком, «Match Spread and Match Total markets… will be deemed void». В парах это обычный формат,
//    значит цена Pinnacle описывает только матчи в два сета, а Betano рассчитывает и трёхсетовые.
//  • Теннис, одиночная квалификация ITF — то же правило 4 (решающий сет там тоже тай-брейк).
//  • Вторая половина в баскетболе и ам. футболе. Pinnacle: «Bets on the Game and 2nd-Half periods include all
//    overtimes». Включает ли овертайм вторая половина у Betano — неизвестно.
//
// ЧТО ОСТАЁТСЯ РАЗНЫМ, НО НЕ ЛОМАЕТ СТАВКУ: отказ игрока в теннисе. Pinnacle: победа в матче рассчитывается, если
// сыгран хотя бы сет, остальные рынки аннулируются, если отрезок не доигран. Как поступает Betano — не прочитано.
// Мы ставим только плечо Betano: при отказе ставку вернут или рассчитают, противоположного плеча у нас нет.
const { parseKey } = require("./markets.cjs");

const TENNIS = 3;

// PURE: ctx = { sport, t1, t2, league, pLeague }. Возврат null (сравнивать можно) или строка с причиной.
function ruleBlock(key, ctx = {}) {
  const k = parseKey(key);
  const sport = Number(ctx.sport);
  if (k.period === "/Half/Main/2") return "вторая половина: у Pinnacle включает овертайм, у Betano неизвестно";
  if (sport === TENNIS && k.period === "/Main/Main/Game" && (k.family === "hc" || k.family === "tot")) {
    const leagues = String(ctx.league || "") + " " + String(ctx.pLeague || "");
    const doubles = /\//.test(String(ctx.t1 || "")) || /\//.test(String(ctx.t2 || "")) || /doubles/i.test(leagues);
    if (doubles) return "теннис, пары: Pinnacle аннулирует фору и тотал геймов, если решающий сет — тай-брейк";
    if (/\bITF\b/i.test(leagues) && /qualif|\bQ\d\b/i.test(leagues)) return "теннис, квалификация ITF: решающий сет — тай-брейк, Pinnacle аннулирует фору и тотал геймов";
  }
  return null;
}

module.exports = { ruleBlock };
